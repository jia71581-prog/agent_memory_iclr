def acc(a, qs): return sum(J[a][q] for q in qs) / len(qs)
def f1m(a, qs): return sum(F[a][q] for q in qs) / len(qs)
def mc(b, c):
    n = b + c
    if n == 0: return 1.0
    k = min(b, c)
    return min(1.0, 2 * sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n)
def bc(a, ref, qs):
    return (sum(1 for q in qs if J[a][q] and not J[ref][q]),
            sum(1 for q in qs if not J[a][q] and J[ref][q]))
RNG = np.random.default_rng(20260917)
import hashlib
def _rng(tag):
    # per-call deterministic seed (stable across processes: md5, not salted hash())
    h = int(hashlib.md5(tag.encode()).hexdigest()[:8], 16)
    return np.random.default_rng(h ^ 20260917)
def _tag(qs):
    return hashlib.md5("|".join(qs).encode()).hexdigest()[:12]
def boot(a, ref, qs, metric="judge", reps=20000):
    S = J if metric == "judge" else F
    d = np.array([float(S[a][q]) - float(S[ref][q]) for q in qs])
    g = _rng(f"{a}|{ref}|{metric}|{len(qs)}|{_tag(qs)}")
    idx = g.integers(0, len(d), size=(reps, len(d)))
    m = d[idx].mean(axis=1)
    return d.mean(), float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5))
def bootacc(a, qs, reps=20000):
    x = np.array([float(J[a][q]) for q in qs])
    g = _rng(f"acc|{a}|{len(qs)}|{_tag(qs)}")
    idx = g.integers(0, len(x), size=(reps, len(x)))
    m = x[idx].mean(axis=1)
    return x.mean(), float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5))
def holm(items):
    m = len(items); out = {}; run = 0.0
    for i, (k, p) in enumerate(sorted(items, key=lambda kv: kv[1])):
        run = max(run, min(1.0, (m - i) * p)); out[k] = run
    return out
def star(p):
    return "***" if p < 0.001 else "**" if p < 0.01 else "*" if p < 0.05 else "n.s."
def pfmt(p):
    return f"{p:.2e}" if p < 1e-3 else f"{p:.4f}"

